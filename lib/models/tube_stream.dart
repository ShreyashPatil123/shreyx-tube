class TubeVideoStream {
  final String url;
  final String resolution;
  final int width;
  final int height;
  final String container;
  final String mimeType;
  final String codec;
  final int fps;
  final int bitrate;
  final bool isVideoOnly;
  final String deliveryMethod;
  final String manifestType;
  final bool isLive;
  String? pairedAudioUrl;

  TubeVideoStream({
    required this.url,
    required this.resolution,
    required this.width,
    required this.height,
    required this.container,
    required this.mimeType,
    required this.codec,
    required this.fps,
    required this.bitrate,
    required this.isVideoOnly,
    required this.deliveryMethod,
    required this.manifestType,
    this.isLive = false,
    this.pairedAudioUrl,
  });

  factory TubeVideoStream.fromMap(Map<dynamic, dynamic> map) {
    return TubeVideoStream(
      url: map['url']?.toString() ?? '',
      resolution: map['resolution']?.toString() ?? '${map['height'] ?? 0}p',
      width: (map['width'] as num?)?.toInt() ?? 0,
      height: (map['height'] as num?)?.toInt() ?? 0,
      container: map['container']?.toString() ?? 'mp4',
      mimeType: map['mimeType']?.toString() ?? 'video/mp4',
      codec: map['codec']?.toString() ?? '',
      fps: (map['fps'] as num?)?.toInt() ?? 30,
      bitrate: (map['bitrate'] as num?)?.toInt() ?? 0,
      isVideoOnly: map['isVideoOnly'] == true,
      deliveryMethod: map['deliveryMethod']?.toString() ?? 'PROGRESSIVE',
      manifestType: map['manifestType']?.toString() ?? 'PROGRESSIVE',
      isLive: map['isLive'] == true,
      pairedAudioUrl: map['pairedAudioUrl']?.toString(),
    );
  }

  Map<String, dynamic> toMediaParams(
      {int startPositionMs = 0, bool autoPlay = true}) {
    return {
      'videoUrl': url,
      'audioUrl': pairedAudioUrl,
      'deliveryMethod': deliveryMethod,
      'mimeType': mimeType,
      'container': container,
      'startPositionMs': startPositionMs,
      'autoPlay': autoPlay,
      'isLive': isLive,
    };
  }

  @override
  String toString() {
    return '$resolution ($container/$codec, ${fps}fps, ${bitrate ~/ 1000}kbps, ${isVideoOnly ? "Adaptive" : "Muxed"})';
  }
}

